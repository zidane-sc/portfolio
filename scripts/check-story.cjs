const assert = require('node:assert/strict')
const { chromium } = require('playwright-core')
;(async () => {
 const browser = await chromium.launch({executablePath: `${process.env.HOME}/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome`})
 for(const [width,height] of [[320,568],[390,844],[412,915],[844,390]]){
  const page = await browser.newPage({viewport:{width,height},isMobile:true,hasTouch:true})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:4181/portfolio-v2/',{waitUntil:'domcontentloaded'})
  await page.locator('.mobile-story').waitFor()
  await page.getByRole('button',{name:'Explore the work'}).click()
  await page.waitForTimeout(700)
  assert.equal(await page.locator('.story-page:not([inert])').count(),1)
  assert.match(await page.locator('.story-page:not([inert])').innerText(),/Dealls/)
  if(width===390) await page.screenshot({path:'/tmp/portrait-story-overview.png'})
  await page.locator('.story-page:not([inert])').getByRole('button',{name:'Engineering decisions'}).click();await page.waitForTimeout(700)
  assert.match(await page.locator('.story-page:not([inert])').innerText(),/What I built/)
  if(width===390) await page.screenshot({path:'/tmp/portrait-story-engineering.png'})
  await page.getByLabel('Choose project').selectOption({label: await page.locator('select option').filter({hasText:'PT Kamiko'}).innerText()});await page.waitForTimeout(700)
  await page.locator('.story-page:not([inert])').getByRole('button',{name:'Deliverables',exact:true}).click();await page.waitForTimeout(700)
  assert.match(await page.locator('.story-page:not([inert])').innerText(),/Industrial Modbus Bridge|Manufacturing ERP|Asset Maintenance/)
  const dimensions=await page.evaluate(()=>{
   const nav=[...document.querySelectorAll('.story-footer button')].map(e=>{const r=e.getBoundingClientRect();return {w:r.width,h:r.height,right:r.right}})
   return {w:innerWidth,sw:document.documentElement.scrollWidth,zoom:getComputedStyle(document.querySelector('.story-page')).zoom,nav}
  })
  assert.equal(dimensions.sw,dimensions.w)
  assert.equal(dimensions.zoom,'1')
  assert(dimensions.nav.every(r=>r.w>=44&&r.h>=44&&r.right<=width))
  assert.deepEqual(errors,[])
  console.log(`PASS story ${width}x${height}: navigation, project jump, image dialog, no zoom, controls`)
  await page.close()
 }
 const p=await browser.newPage({viewport:{width:1920,height:1080}})
 await p.goto('http://127.0.0.1:4181/portfolio-v2/',{waitUntil:'domcontentloaded'})
 assert.equal(await p.locator('.slide').count(),await p.locator('#slide-picker option').count())
 assert.equal(await p.locator('.mobile-story').count(),0)
 console.log('PASS desktop: data-driven slide deck retained')
 await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
